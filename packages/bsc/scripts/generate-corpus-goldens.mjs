/**
 * Generate hand-reviewable BSC golden files for every corpus project.
 * Output: fixtures/corpus/bsc/<project-id>.bsc.json
 *
 * Prefer: npm run bsc:golden  (from monorepo root)
 */
import fs from "node:fs";
import path from "node:path";
import { parseKicadProjectDir } from "../../../workers/parser/src/index.ts";
import { generateBSC } from "../src/index.ts";

function findRoot(start) {
  let dir = start;
  for (let i = 0; i < 5; i++) {
    if (fs.existsSync(path.join(dir, "fixtures/corpus/manifest.json"))) return dir;
    dir = path.dirname(dir);
  }
  return start;
}
const repoRoot = findRoot(process.cwd());
const manifestFile = path.join(repoRoot, "fixtures/corpus/manifest.json");
const goldenDir = path.join(repoRoot, "fixtures/corpus/bsc");

fs.mkdirSync(goldenDir, { recursive: true });
const manifest = JSON.parse(fs.readFileSync(manifestFile, "utf8"));

const summary = [];

for (const project of manifest.projects) {
  const rev =
    project.revisions.find((r) => r.label === "newer" && r.status === "ok") ||
    project.revisions.find((r) => r.status === "ok");
  if (!rev) {
    console.warn("skip", project.id);
    continue;
  }
  const abs = path.resolve(repoRoot, rev.path);
  const snap = parseKicadProjectDir(abs);
  const bsc = generateBSC(snap, {
    boardName: project.id,
    revision: rev.label,
    revisionId: rev.commitSha ?? null,
  });
  const outPath = path.join(goldenDir, `${project.id}.bsc.json`);
  fs.writeFileSync(outPath, JSON.stringify(bsc, null, 2) + "\n");
  summary.push({
    project: project.id,
    mcus: bsc.mcus.length,
    pins: bsc.pins.length,
    busDevices: bsc.busDevices.length,
    powerRails: bsc.powerRails.length,
    connectors: bsc.connectors.length,
    testPoints: bsc.testPoints.length,
    revStraps: bsc.revStraps.length,
    notes: bsc.confidenceNotes.length,
    file: path.relative(repoRoot, outPath).replace(/\\/g, "/"),
  });
  console.log(
    `${project.id.padEnd(32)} mcus=${String(bsc.mcus.length).padStart(2)} pins=${String(bsc.pins.length).padStart(5)} rails=${String(bsc.powerRails.length).padStart(4)} bus=${String(bsc.busDevices.length).padStart(3)} conn=${String(bsc.connectors.length).padStart(3)} tp=${String(bsc.testPoints.length).padStart(3)} → ${path.basename(outPath)}`,
  );
}

fs.writeFileSync(
  path.join(goldenDir, "INDEX.md"),
  [
    "# Corpus Board Support Contracts",
    "",
    "Generated by `npm run bsc:golden -w @solderlab/bsc`.",
    "Review by hand — detectors refuse to guess (null + confidenceNotes).",
    "",
    "| Project | MCUs | Pins | Rails | Bus | Conn | TP | RevStraps | File |",
    "|---|---:|---:|---:|---:|---:|---:|---:|---|",
    ...summary.map(
      (s) =>
        `| ${s.project} | ${s.mcus} | ${s.pins} | ${s.powerRails} | ${s.busDevices} | ${s.connectors} | ${s.testPoints} | ${s.revStraps} | \`${path.basename(s.file)}\` |`,
    ),
    "",
  ].join("\n"),
);

console.log(`\nWrote ${summary.length} goldens + INDEX.md → ${goldenDir}`);
